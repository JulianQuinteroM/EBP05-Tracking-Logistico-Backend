CREATE TABLE cuenta_usuario (
  username VARCHAR(100) PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  rol VARCHAR(20) NOT NULL CHECK (rol IN ('ADMIN','OPERADOR','REPARTIDOR','VIEWER')),
  permisos VARCHAR(500) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE sesion_usuario (
  token_hash VARCHAR(64) PRIMARY KEY,
  username VARCHAR(100) NOT NULL REFERENCES cuenta_usuario(username),
  expira_en TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_sesion_expira ON sesion_usuario(expira_en);
CREATE TABLE contacto (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  documento VARCHAR(30) UNIQUE,
  correo VARCHAR(254) NOT NULL UNIQUE,
  telefono VARCHAR(30) NOT NULL,
  version BIGINT NOT NULL DEFAULT 0
);
ALTER TABLE envio ADD COLUMN remitente_contacto_id BIGINT REFERENCES contacto(id);
ALTER TABLE envio ADD COLUMN destinatario_contacto_id BIGINT REFERENCES contacto(id);
CREATE INDEX ix_envio_remitente ON envio(remitente_contacto_id);
CREATE INDEX ix_envio_destinatario ON envio(destinatario_contacto_id);
CREATE TABLE evidencia_entrega (
  envio_id BIGINT PRIMARY KEY REFERENCES envio(id),
  receptor VARCHAR(120) NOT NULL,
  tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('FOTO','FIRMA')),
  mime VARCHAR(30) NOT NULL,
  contenido BYTEA NOT NULL,
  actor VARCHAR(100) NOT NULL,
  ocurrido_en TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE intento_entrega (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  envio_id BIGINT NOT NULL REFERENCES envio(id),
  numero INTEGER NOT NULL,
  motivo VARCHAR(500) NOT NULL,
  proxima_fecha DATE NOT NULL,
  actor VARCHAR(100) NOT NULL,
  ocurrido_en TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE(envio_id, numero)
);
CREATE TABLE reclamacion (
  id VARCHAR(40) PRIMARY KEY,
  envio_id BIGINT NOT NULL REFERENCES envio(id),
  clave_hash VARCHAR(64) NOT NULL,
  categoria VARCHAR(30) NOT NULL,
  asunto VARCHAR(150) NOT NULL,
  descripcion VARCHAR(3000) NOT NULL,
  correo VARCHAR(254) NOT NULL,
  estado VARCHAR(25) NOT NULL CHECK (estado IN ('ABIERTA','EN_REVISION','RESUELTA','CERRADA')),
  responsable VARCHAR(100) REFERENCES cuenta_usuario(username),
  creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
  actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX ix_reclamacion_estado ON reclamacion(estado, creado_en);
CREATE TABLE mensaje_reclamacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reclamacion_id VARCHAR(40) NOT NULL REFERENCES reclamacion(id),
  autor VARCHAR(100) NOT NULL,
  texto VARCHAR(3000) NOT NULL,
  ocurrido_en TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE analisis_ia (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reclamacion_id VARCHAR(40) NOT NULL REFERENCES reclamacion(id),
  modelo VARCHAR(100) NOT NULL,
  resultado TEXT NOT NULL,
  actor VARCHAR(100) NOT NULL,
  ocurrido_en TIMESTAMP WITH TIME ZONE NOT NULL
);
